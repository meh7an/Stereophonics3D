const GLYPHS: usize = 95;
const FIRST: u8 = 0x20;
/// Drawn for characters the font lacks.
const UNKNOWN: u8 = b'?';

/// Size of the font uniform buffer: `uvec4 words[48]` in std140, the glyph bytes packed
/// little-endian, four per word.
pub const FONT_BYTES: usize = 48 * 16;

/// The font as the uniform buffer's bytes, zero-padded.
pub fn font_bytes() -> [u8; FONT_BYTES] {
    let mut bytes = [0; FONT_BYTES];
    for (target, source) in bytes.iter_mut().zip(FONT.as_flattened()) {
        *target = *source;
    }
    bytes
}

/// One character cell: an instance of the text pass.
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Cell {
    /// Top-left corner, in pixels.
    pub x: f32,
    pub y: f32,
    /// Index into the font.
    pub glyph: u32,
    /// RGBA8, red in the low byte, as `unpackUnorm4x8` reads it.
    pub color: u32,
}

pub const CELL_BYTES: usize = size_of::<Cell>();
/// Longest line drawn; longer lines are cut.
const MAX_COLUMNS: usize = 96;
const MAX_LINES: usize = 8;
/// Cells in the largest panel: the lines plus a one-cell border all round.
pub const MAX_CELLS: usize = (MAX_COLUMNS + 2) * (MAX_LINES + 2);

/// Pixels per font pixel: 2 at 720 lines, 3 at 1080, at most 4.
pub fn scale(extent: vk::Extent2D) -> u32 {
    (extent.height / 360).clamp(1, 4)
}

/// Lays `lines` out as a panel in the top-left corner of an image of `extent`, one cell
/// from each edge, cutting lines and rows that do not fit.
pub fn layout(lines: &[Line], extent: vk::Extent2D) -> Vec<Cell> {
    let cell = 8 * scale(extent);
    let fit = |pixels: u32| (pixels / cell).saturating_sub(4) as usize;
    let columns = fit(extent.width).min(MAX_COLUMNS);
    let rows = fit(extent.height).min(MAX_LINES).min(lines.len());
    if columns == 0 || rows == 0 {
        return Vec::new();
    }
    let lines = &lines[..rows];
    let width = lines
        .iter()
        .map(|(text, _)| text.chars().count().min(columns))
        .max()
        .unwrap_or(0);
    let border = lines.first().map_or([255; 4], |(_, color)| *color);
    let mut cells = Vec::with_capacity((width + 2) * (rows + 2));
    for row in 0..rows + 2 {
        let line = row.checked_sub(1).and_then(|index| lines.get(index));
        let color = line.map_or(border, |(_, color)| *color);
        let mut text = line.map(|(text, _)| text.chars()).into_iter().flatten();
        for column in 0..width + 2 {
            let character = if (1..=width).contains(&column) {
                text.next().unwrap_or(' ')
            } else {
                ' '
            };
            cells.push(Cell {
                x: ((column as u32 + 1) * cell) as f32,
                y: ((row as u32 + 1) * cell) as f32,
                glyph: glyph(character),
                color: u32::from_le_bytes(color),
            });
        }
    }
    cells
}

/// The font index of `character`, or of `?` when the font lacks it.
fn glyph(character: char) -> u32 {
    let byte = u8::try_from(character)
        .ok()
        .filter(|byte| (FIRST..FIRST + GLYPHS as u8).contains(byte))
        .unwrap_or(UNKNOWN);
    u32::from(byte - FIRST)
}

#[cfg(test)]
mod tests {
    use super::*;

    const HD: vk::Extent2D = vk::Extent2D {
        width: 1280,
        height: 720,
    };

    #[test]
    fn test_font_matches_known_glyphs() {
        assert_eq!(FONT[0], [0; 8]);
        assert_eq!(
            FONT[usize::from(b'A' - FIRST)],
            [0x0C, 0x1E, 0x33, 0x33, 0x3F, 0x33, 0x33, 0x00]
        );
        let bytes = font_bytes();
        assert_eq!(bytes[8 * usize::from(b'A' - FIRST)], 0x0C);
        assert!(bytes[GLYPHS * 8..].iter().all(|&byte| byte == 0));
    }

    #[test]
    fn test_scale_follows_height() {
        let at = |height| scale(vk::Extent2D { width: 1, height });
        assert_eq!(
            (at(200), at(720), at(1080), at(1440), at(2160)),
            (1, 2, 3, 4, 4)
        );
    }

    #[test]
    fn test_layout_pads_lines_into_a_bordered_block() {
        let lines = [
            ("ab".to_owned(), [1, 2, 3, 4]),
            ("xyz".to_owned(), [9, 9, 9, 9]),
        ];
        let cells = layout(&lines, HD);
        // Three text columns plus borders, two lines plus borders.
        assert_eq!(cells.len(), 5 * 4);
        let cell = 16.0;
        assert_eq!((cells[0].x, cells[0].y), (cell, cell));
        let first_text = &cells[5 + 1];
        assert_eq!((first_text.x, first_text.y), (2.0 * cell, 2.0 * cell));
        assert_eq!(first_text.glyph, glyph('a'));
        assert_eq!(first_text.color, u32::from_le_bytes([1, 2, 3, 4]));
        assert_eq!(cells[5 + 3].glyph, glyph(' '), "short line padded");
        assert_eq!(cells[10 + 3].glyph, glyph('z'));
    }

    #[test]
    fn test_layout_cuts_long_lines_and_replaces_unknown_characters() {
        let long = ("x".repeat(500), [255; 4]);
        let cells = layout(&[long], HD);
        // 1280 / 16 = 80 cells, minus 4 for margins and borders.
        assert_eq!(cells.len(), (76 + 2) * 3);
        let unknown = layout(&[("\u{e9}".to_owned(), [255; 4])], HD);
        assert_eq!(unknown[3 + 1].glyph, glyph('?'));
        assert!(layout(&[], HD).is_empty());
        let tiny = vk::Extent2D {
            width: 24,
            height: 24,
        };
        assert!(layout(&[long_line()], tiny).is_empty());
    }

    fn long_line() -> Line {
        ("text".to_owned(), [255; 4])
    }
}
